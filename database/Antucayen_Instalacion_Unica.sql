-- Completar equivalencia para CADA par producto-proveedor que aun no la
-- tenga; esto conserva los codigos CSP-00123 y CSP-00122 preexistentes.
-- Codigo ilustrativo estable: PREFIJO_PROVEEDOR-SKU.
-- Se usan prefijos independientes aun cuando varios proveedores venden el
-- mismo SKU; p.ej. ALV-BEB-0020, CMW-BEB-0020, EMB-BEB-0020.
INSERT INTO equivalencia (id_proveedor, codigo_interno_proveedor, sku)
SELECT
    pp.id_proveedor,
    CONCAT(CASE pp.id_proveedor
        WHEN 2 THEN 'CSP'
        WHEN 3 THEN 'ALV'
        WHEN 4 THEN 'CMW'
        WHEN 5 THEN 'REN'
        WHEN 6 THEN 'EMB'
        WHEN 7 THEN 'CCU'
        WHEN 8 THEN 'SOP'
        WHEN 9 THEN 'COL'
        WHEN 10 THEN 'CRZ'
        WHEN 11 THEN 'EVC'
        WHEN 12 THEN 'CLP'
        WHEN 13 THEN 'CMP'
        END, '-', pp.sku),
    pp.sku
FROM producto_proveedor AS pp
LEFT JOIN equivalencia AS e
    ON e.id_proveedor = pp.id_proveedor AND e.sku = pp.sku
WHERE e.sku IS NULL;
